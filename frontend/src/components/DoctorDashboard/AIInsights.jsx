import { FaLightbulb, FaBrain, FaCalendarCheck, FaUsers } from "react-icons/fa";

import "./AIInsights.css";

/* ============================================================
   AI-ASSISTED INSIGHTS

   Every number here is a simple, transparent arithmetic summary
   computed from the real `patients` and `assessments` arrays
   already loaded by the dashboard — counts and percentages
   only. Nothing is generated by a model or guessed; if there is
   no data yet, the section says so instead of showing a number.
============================================================ */

const AIInsights = ({ patients = [], assessments = [], isLoading = false }) => {
  if (isLoading) {
    return (
      <div className="ai-insights">
        <div className="ai-insights__header">
          <FaLightbulb />
          <h2>AI-Assisted Insights</h2>
        </div>
        <p className="ai-insights__empty">Crunching the numbers...</p>
      </div>
    );
  }

  if (assessments.length === 0) {
    return (
      <div className="ai-insights">
        <div className="ai-insights__header">
          <FaLightbulb />
          <h2>AI-Assisted Insights</h2>
        </div>
        <p className="ai-insights__empty">
          Insights will appear here once AI assessments have been completed
          for your patients.
        </p>
      </div>
    );
  }

  const nonDementedCount = assessments.filter(
    (a) => a.prediction === "Non Demented"
  ).length;

  const nonDementedPct = Math.round(
    (nonDementedCount / assessments.length) * 100
  );

  const attentionCount = assessments.filter(
    (a) => a.prediction === "Mild Dementia" || a.prediction === "Moderate Dementia"
  ).length;

  const sevenDaysAgo = new Date();
  sevenDaysAgo.setDate(sevenDaysAgo.getDate() - 7);

  const recentCount = assessments.filter(
    (a) => a.createdAt && new Date(a.createdAt) >= sevenDaysAgo
  ).length;

  const avgConfidence =
    assessments.filter((a) => typeof a.confidence === "number").length > 0
      ? Math.round(
          assessments
            .filter((a) => typeof a.confidence === "number")
            .reduce((sum, a) => sum + a.confidence, 0) /
            assessments.filter((a) => typeof a.confidence === "number").length
        )
      : null;

  const insights = [
    {
      icon: <FaUsers />,
      text: `${nonDementedPct}% of completed assessments (${nonDementedCount} of ${assessments.length}) show a Non Demented result.`,
    },
    {
      icon: <FaBrain />,
      text: `${attentionCount} assessment${attentionCount === 1 ? "" : "s"} currently show Mild or Moderate Dementia and may need review.`,
    },
    {
      icon: <FaCalendarCheck />,
      text: `${recentCount} assessment${recentCount === 1 ? "" : "s"} completed in the last 7 days.`,
    },
  ];

  if (avgConfidence !== null) {
    insights.push({
      icon: <FaLightbulb />,
      text: `Average model confidence across all assessments is ${avgConfidence}%.`,
    });
  }

  return (
    <div className="ai-insights">
      <div className="ai-insights__header">
        <FaLightbulb />
        <h2>AI-Assisted Insights</h2>
      </div>

      <ul className="ai-insights__list">
        {insights.map((insight, index) => (
          <li key={index}>
            <span className="ai-insights__icon">{insight.icon}</span>
            <span>{insight.text}</span>
          </li>
        ))}
      </ul>

      <p className="ai-insights__disclaimer">
        Computed from your current patients and assessments on record.
      </p>
    </div>
  );
};

export default AIInsights;
